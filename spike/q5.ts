import { launch, sleep } from "./lib";
const ctx = await launch();
const p = await ctx.newPage();
const msgs: string[] = [];
p.on("console", (m) => { if (/Refused|Content Security|WebSocket/i.test(m.text())) msgs.push(m.text().slice(0, 300)); });
await p.goto("https://www.twitch.tv/rubius", { waitUntil: "domcontentloaded" });
await sleep(4000);
await p.click("#spike-irc-btn");
await sleep(15000);
const a = await p.evaluate(() => Object.fromEntries([...document.documentElement.attributes].filter((a) => a.name.startsWith("data-spike")).map((a) => [a.name, a.value])));
console.log("irc:", a["data-spike-irc"], "privmsg:", a["data-spike-privmsg"], "pings answered:", a["data-spike-ping"]);
console.log("handshake lines:", a["data-spike-irc-sample"]);
console.log("priv sample:", a["data-spike-priv-sample"]);
console.log("console csp:", msgs);
await ctx.close();
