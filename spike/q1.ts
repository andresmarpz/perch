import { launch, sleep, videoState } from "./lib";
const channel = process.argv[2] ?? "kaicenat";
const t0 = Date.now();
const ctx = await launch();
console.log("version", ctx.browser()?.version());
const p = await ctx.newPage();
p.on("console", (m) => { if (/error|CSP|Refused/i.test(m.text())) console.log("console:", m.text().slice(0, 200)); });
await p.goto(`https://www.twitch.tv/${channel}`, { waitUntil: "domcontentloaded" });
await sleep(8000);
console.log("loaded attr", await p.evaluate(() => document.documentElement.dataset.spikeLoaded));
console.log("dpip in isolated", await p.evaluate(() => document.documentElement.dataset.spikeDpipInIsolated));
console.log("title", await p.title());
console.log("buttons on page:", await p.evaluate(() => [...document.querySelectorAll("button[data-a-target]")].map((b) => b.getAttribute("data-a-target")).join(",")));
console.log("v0", await videoState(p));
await sleep(5000);
console.log("v1", await videoState(p));
await p.screenshot({ path: "/tmp/q1.png" });
await ctx.close();
console.log("secs", (Date.now() - t0) / 1000);
